import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
import os from 'node:os'
import path from 'node:path'

export async function runGeometry3DM2Acceptance({evaluate,until,textButton,click,box,pointer,delay,send,drag}) {
  const fixture=JSON.parse(await fs.readFile(new URL('./geometry_3d_canonical.json',import.meta.url),'utf8'))
  fixture.linear_objects.push({id:'ray_ac',kind:'ray',a:'a',b:'c'},{id:'vector_bc',kind:'vector',a:'b',b:'c'},{id:'segment_cd',kind:'segment',a:'c',b:'d'})
  const frame='[data-frame-id="frame-1"]', viewport=`${frame} .geometry-3d-viewport`
  const camera=()=>evaluate(`JSON.parse(document.querySelector('${viewport}').dataset.editingCamera)`)
  const action=async()=>{
    const editing=await evaluate(`!!document.querySelector('${frame} .geometry-3d-editor')`)
    await click(`${frame} .visual-frame__actions button`)
    await until(`${editing?'!':''}document.querySelector('${frame} .geometry-3d-editor')`)
  }
  await textButton('Həndəsə');await textButton('3D səhnə əlavə et')
  await until('document.body.innerText.includes("3D səhnə boşdur")')
  await until(`document.querySelector('${viewport} canvas')`)
  assert.equal(await evaluate(`document.querySelector('${viewport}').dataset.webglFallback`),'false')
  await action()
  await evaluate(`savedRevision.blocks[0].payload.source_data=${JSON.stringify(fixture)};reloadEditor()`)
  await until(`document.querySelector('${viewport} svg [data-id="ray_ac"]')`)
  assert.ok(await evaluate(`document.querySelector('${viewport} svg [data-id="vector_bc"]')`))
  await click(frame);await action()
  await until(`document.querySelector('${viewport} canvas')`)
  await click('[data-tool-3d="camera"]') // M3 reserves point gestures for semantic editing.
  const original=await camera()
  const printSvg=await evaluate(`document.querySelector('${viewport} .geometry-3d-static').innerHTML`)
  await until(`Number(document.querySelector('${viewport} canvas').dataset.renderCount)>0`)
  await delay(300) // Allow initial resize and ribbon/session registration frames to settle.
  const count=await evaluate(`document.querySelector('${viewport} canvas').dataset.renderCount`)
  await delay(250)
  assert.equal(await evaluate(`document.querySelector('${viewport} canvas').dataset.renderCount`),count,'no idle continuous rendering')
  await drag(`${viewport} canvas`,70,35)
  assert.notDeepEqual(await camera(),original,'real pointer orbit')
  const orbited=await camera(), b=await box(`${viewport} canvas`), x=b.x+b.width/2,y=b.y+b.height/2
  // Phase 2.1 reserves right-click for the frame menu; Ctrl-left is camera pan.
  await pointer('mousePressed',x,y,{button:'left',buttons:1,modifiers:2,clickCount:1})
  await pointer('mouseMoved',x+20,y+20,{button:'left',buttons:1,modifiers:2});await pointer('mouseReleased',x+20,y+20,{button:'left',modifiers:2,clickCount:1});await delay(100)
  assert.notDeepEqual((await camera()).target,orbited.target,'real pointer pan')
  const span=(await camera()).vertical_span
  await pointer('mouseWheel',x,y,{deltaY:-120,deltaX:0});await delay(150)
  assert.notEqual((await camera()).vertical_span,span,'wheel zoom')
  assert.deepEqual(await evaluate('savedRevision.blocks[0].payload.source_data.print_camera'),fixture.print_camera,'navigation never persists')
  assert.equal(await evaluate('document.querySelector(\'[aria-label="Geri al"]\').disabled'),true,'camera gestures create no Undo entries')
  assert.equal(await evaluate(`document.querySelector('${viewport} .geometry-3d-static').innerHTML`),printSvg,'editing navigation leaves print SVG fixed')
  const screenshot=await send('Page.captureScreenshot',{format:'png'})
  await fs.writeFile(path.join(os.tmpdir(),'geometry-3d-m2-acceptance.png'),Buffer.from(screenshot.result.data,'base64'))
  for(const view of ['front','back','left','right','top','bottom','isometric'])await click(`[data-view="${view}"]`)
  const saved=await camera()
  await textButton('Sual üçün görünüşü təyin et')
  await click('[aria-label="Geri al"]');await action()
  assert.deepEqual(await evaluate('savedRevision.blocks[0].payload.source_data.print_camera'),fixture.print_camera,'saved-camera Undo')
  await action();assert.deepEqual(await camera(),saved,'session camera survives edit-mode switch');await click('[data-view="isometric"]');await textButton('Sual üçün görünüşü təyin et')
  await click('[aria-label="Geri al"]');await click('[aria-label="Yenidən et"]')
  await click('[data-view="top"]');await action()
  const printCamera=await evaluate('structuredClone(savedRevision.blocks[0].payload.source_data.print_camera)')
  assert.notDeepEqual(printCamera,fixture.print_camera)
  assert.ok(printCamera.position.every(Number.isFinite))
  await click(frame);await until(`document.querySelector('${frame} [data-handle="se"]')`)
  await drag(`${frame} [data-handle="se"]`,40,30)
  await click(`${frame} .visual-frame__actions button:nth-child(2)`)
  await until('[...document.querySelectorAll("button")].some(b=>b.textContent.trim()==="Çərçivə əlavə et"&&!b.disabled)')
  const size=await box(viewport);assert.ok(size.width>520)
  await textButton('Çərçivə əlavə et');await until('document.querySelector(".geometry-authoring-board svg")')
  await click('[data-frame-id="frame-2"] .visual-frame__actions button')
  await evaluate('reloadEditor()');await until(`document.querySelector('${viewport} svg [data-id="a"]')`)
  assert.deepEqual(await evaluate('savedRevision.blocks[0].payload.source_data.print_camera'),printCamera)
  assert.equal(await evaluate('savedRevision.blocks[1].payload.source_data.schema_version'),1)
  await click(frame);await action();await until(`document.querySelector('${viewport} canvas')`)
  // The existing platform intentionally prints only .pdf-export-document content.
  await evaluate(`document.querySelector('${frame}').classList.add('pdf-export-document')`)
  await send('Emulation.setEmulatedMedia',{media:'print'})
  assert.equal(await evaluate(`getComputedStyle(document.querySelector('${viewport} canvas')).display`),'none')
  assert.equal(await evaluate(`getComputedStyle(document.querySelector('${viewport} .geometry-3d-static')).visibility`),'visible')
  await send('Emulation.setEmulatedMedia',{media:''})
  await evaluate(`document.querySelector('${frame}').classList.remove('pdf-export-document')`)
  const context=await evaluate(`(()=>{const c=document.querySelector('${viewport} canvas');return !!c.getContext('webgl2')})()`)
  assert.equal(context,true,'actual WebGL2 context')
  await evaluate(`document.querySelector('${viewport} canvas').getContext('webgl2').getExtension('WEBGL_lose_context').loseContext()`)
  await until('document.body.innerText.includes("WebGL əlçatan deyil")')
  assert.equal(await evaluate(`getComputedStyle(document.querySelector('${viewport} .geometry-3d-static')).visibility`),'visible')
  await action();assert.deepEqual(await evaluate('savedRevision.blocks[0].payload.source_data.print_camera'),printCamera)
  await evaluate(`window.openUnframedScene(${JSON.stringify(fixture)})`)
  await until('document.querySelector(".geometry-3d-viewport canvas")')
  await click('[data-view="front"]');await textButton('Sual üçün görünüşü təyin et')
  assert.notDeepEqual(await evaluate('unframedScene.print_camera'),fixture.print_camera)
  // Explicit initialization failure, in addition to real context-loss acceptance above.
  await evaluate(`window.originalGetContext=HTMLCanvasElement.prototype.getContext;HTMLCanvasElement.prototype.getContext=function(type,...args){if(type.startsWith('webgl'))return null;return window.originalGetContext.call(this,type,...args)};window.openUnframedScene(${JSON.stringify(fixture)})`)
  await until('document.body.innerText.includes("WebGL əlçatan deyil")')
  assert.ok(await evaluate('document.querySelector(".geometry-3d-static svg [data-id=ray_ac]")'))
  await click('[data-view="top"]');await textButton('Sual üçün görünüşü təyin et')
  assert.notDeepEqual(await evaluate('unframedScene.print_camera'),fixture.print_camera,'document editing works without WebGL')
  await evaluate('HTMLCanvasElement.prototype.getContext=window.originalGetContext')
  assert.ok(saved)
  console.log('PASS: real Edge M2 WebGL2 empty/nonempty semantic fixtures, orbit/pan/zoom, seven views, saved-camera Undo/Redo/isolation, frame resize, mixed V1/V2 save/reload, unframed editor, context loss and forced WebGL initialization fallback (fixture API)')
}
