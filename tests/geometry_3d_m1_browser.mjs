import assert from 'node:assert/strict'

export async function runGeometry3DM1Acceptance({ evaluate, until, textButton, click, send, drag }) {
  await textButton('Həndəsə'); await textButton('3D səhnə əlavə et')
  const frame = '[data-frame-id="frame-1"]'
  await until(`document.querySelector('${frame} summary')`)
  await click(`${frame} summary`)
  await until(`document.querySelector('${frame} [aria-label="3D səhnə təsviri"]')`)
  assert.equal(await evaluate('savedRevision.blocks[0].payload.source_data.schema_version'), 2)
  assert.ok(await evaluate('document.body.innerText.includes("3D səhnə boşdur")'))
  assert.equal(await evaluate(`document.querySelectorAll('${frame} [data-handle]').length`), 8)
  const input = async (selector, value) => {
    await click(selector)
    await send('Input.dispatchKeyEvent', { type: 'keyDown', key: 'a', code: 'KeyA', modifiers: 2, windowsVirtualKeyCode: 65 })
    await send('Input.dispatchKeyEvent', { type: 'keyUp', key: 'a', code: 'KeyA', modifiers: 2, windowsVirtualKeyCode: 65 })
    await send('Input.insertText', { text: value })
  }
  await input('[aria-label="3D səhnə təsviri"]', 'M1 Edge səhnəsi')
  await click('[aria-label="Sual kamerası X"]') // description blur is one committed edit
  await click('[aria-label="Geri al"]')
  await until(`document.querySelector('[aria-label="3D səhnə təsviri"]').value === '3D həndəsə səhnəsi'`)
  await click('[aria-label="Yenidən et"]')
  await until(`document.querySelector('[aria-label="3D səhnə təsviri"]').value === 'M1 Edge səhnəsi'`)
  await input('[aria-label="Sual kamerası X"]', '6')
  await textButton('Sual görünüşünü tətbiq et')
  await click('[aria-label="Geri al"]')
  await until(`document.querySelector('[aria-label="Sual kamerası X"]').value === '4'`)
  await click('[aria-label="Yenidən et"]')
  await until(`document.querySelector('[aria-label="Sual kamerası X"]').value === '6'`)
  await input('[aria-label="Sual kamerası X"]', '1000000000001')
  await textButton('Sual görünüşünü tətbiq et')
  await until('document.querySelector("[role=alert]")')
  await click('[aria-label="Geri al"]') // invalid edit added no entry, goes back to camera X=4
  await until(`document.querySelector('[aria-label="Sual kamerası X"]').value === '4'`)
  await click('[aria-label="Yenidən et"]')
  await click(`${frame} .visual-frame__actions button`)
  await until(`!document.querySelector('${frame} [aria-label="3D səhnə təsviri"]')`)
  const saved = await evaluate('structuredClone(savedRevision.blocks[0].payload.source_data)')
  assert.equal(saved.description, 'M1 Edge səhnəsi'); assert.equal(saved.print_camera.position[0], 6)
  await click(frame)
  await drag(`${frame} [data-handle="se"]`, 40, 40)
  await click(`${frame} .visual-frame__actions button:nth-child(2)`)
  await until('requests.some(r=>r.url.endsWith("/visual-placement"))')
  assert.deepEqual(await evaluate('savedRevision.blocks[0].payload.source_data'), saved, 'frame save preserves scene')
  await textButton('Çərçivə əlavə et')
  await until('document.querySelector(".geometry-authoring-board svg")')
  await click('[data-frame-id="frame-2"] .visual-frame__actions button')
  await until('savedRevision.blocks.length === 2 && !document.querySelector(".geometry-authoring-board")')
  const legacy = await evaluate('structuredClone(savedRevision.blocks[1].payload.source_data)')
  assert.equal(legacy.schema_version, 1)
  await evaluate('reloadEditor()')
  await until(`document.querySelector('${frame} [data-geometry-version="2"]') && document.querySelector('[data-frame-id="frame-2"]')`)
  assert.deepEqual(await evaluate('savedRevision.blocks[0].payload.source_data'), saved)
  await click(frame); await click(`${frame} .visual-frame__actions button`)
  await until(`document.querySelector('${frame} summary')`)
  await click(`${frame} summary`)
  await until(`document.querySelector('[aria-label="3D səhnə təsviri"]')`)
  await input('[aria-label="3D səhnə təsviri"]', 'Ləğv edilən dəyişiklik')
  await click('[aria-label="Sual kamerası X"]'); await textButton('Ləğv et')
  assert.deepEqual(await evaluate('savedRevision.blocks[0].payload.source_data'), saved)
  assert.deepEqual(await evaluate('savedRevision.blocks[1].payload.source_data'), legacy)
  await evaluate('window.confirm=()=>true')
  await click(frame); await click(`${frame} .visual-frame__actions button:nth-child(3)`)
  await until(`savedRevision.blocks.length === 1 && !document.querySelector('[data-geometry-version="2"]')`)
  assert.deepEqual(await evaluate('savedRevision.blocks[0].payload.source_data'), legacy)
  console.log('PASS: real Edge M1 create/select/edit, description and saved-camera Undo/Redo, invalid rejection, frame save, mixed V1/V2 reload, cancel and block deletion (fixture API; no 3D rendering claim)')
}
